import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL("src/project-host/entry.mjs", root))],
  outfile: fileURLToPath(new URL("dist/project-host/launcher.mjs", root)),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  metafile: true,
  legalComments: "inline",
  banner: {
    js: "// Generated by ds-skills. Do not edit; run explicit project setup to refresh.",
  },
});
for (const output of Object.values(result.metafile.outputs))
  if (
    output.imports.some(
      (item) => !item.external || !item.path.startsWith("node:"),
    )
  )
    throw new Error(
      "Project launcher must be self-contained except for Node built-ins",
    );
